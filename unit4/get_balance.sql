CREATE OR REPLACE FUNCTION get_balance(num IN NUMBER,NO1 OUT NUMBER)
RETURN NUMBER
IS
BEGIN
    SELECT BALANCE INTO NO1
    FROM ACCOUNT
    WHERE ACNO = num;

