CREATE OR REPLACE TRIGGER gender_title
BEFORE INSERT OR UPDATE OF ENAME,GENDER ON EMP 
FOR EACH ROW
BEGIN

IF:NEW.ENAME NOT LIKE'MR.%'AND :NEW.ENAME
NOT LIKE 'MS.%'THEN

	IF UPPER(:NEW.GENDER)+= 'M' THEN
		:NEW.ENAME :='MR.'||:NEW.ENAME;
		ELSIF UPPER(:NEW.GENDER)='F'THEN
	END IF;
	END IF;
END;
